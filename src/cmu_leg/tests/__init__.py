"""Replay and validation harnesses.

Each one re-runs a ported controller against the baseline log in `data/` and
writes a figure. Figures go to `tests/plots/`, which is gitignored -- they are
regenerated by running the harness, so they do not belong in history.
"""
from pathlib import Path

PLOTS = Path(__file__).parent / "plots"


def plot_path(name: str) -> Path:
    """`tests/plots/<name>`, with the directory created on first use."""
    PLOTS.mkdir(exist_ok=True)
    return PLOTS / name
