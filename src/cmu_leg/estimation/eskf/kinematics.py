"""Symbolic forward kinematics scratchpad.

Template for composing homogeneous transforms g in SE(3) with sagittal-plane
(y-axis) revolute joints. Run directly to print the composed transform:

    python -m cmu_leg.estimation.eskf.kinematics
"""

import sympy as sp


def rot_y(theta: sp.Expr) -> sp.Matrix:
    """Rotation matrix about the y axis by theta."""
    c, s = sp.cos(theta), sp.sin(theta)
    return sp.Matrix([[c, 0, s], [0, 1, 0], [-s, 0, c]])


def g_from(R: sp.Matrix, p: sp.Matrix) -> sp.Matrix:
    """Homogeneous transform from rotation R and translation p."""
    return sp.Matrix(sp.BlockMatrix([[R, p], [sp.zeros(1, 3), sp.ones(1, 1)]]))


def g_rot_y(theta: sp.Expr, p: sp.Matrix) -> sp.Matrix:
    """Transform: rotate theta about y at the parent origin, then translate
    along p (expressed in the rotated child frame). The joint therefore sits
    at the parent origin and q does move the child origin.
    """
    R = rot_y(theta)
    return g_from(R, R * p)


def se3_inv(g: sp.Matrix) -> sp.Matrix:
    """Analytic inverse of g in SE(3): [R.T, -R.T @ p].

    Use this instead of g.inv(). Sympy's generic matrix inverse does not know g
    is rigid and manufactures 1/cos terms that simplify() cannot undo -- e.g. it
    returns the body Jacobian's leading entry as
        -l_shank*sin(k)*tan(a + k) + l_shank*cos(a)/cos(a + k) + l_thigh
    where this form gives the equivalent, readable  l_shank*cos(k) + l_thigh.
    """
    R = g[:3, :3]
    return g_from(R.T, -R.T * g[:3, 3])


def hat(w: sp.Matrix) -> sp.Matrix:
    """Skew-symmetric matrix of a 3-vector (so hat(a) @ b == a x b)."""
    return sp.Matrix([[0, -w[2], w[1]], [w[2], 0, -w[0]], [-w[1], w[0], 0]])


def vee_se3(xi_hat: sp.Matrix) -> sp.Matrix:
    """Unhat a 4x4 twist matrix into a 6-vector, MLS ordering: [v; omega]."""
    return sp.Matrix([
        xi_hat[0, 3], xi_hat[1, 3], xi_hat[2, 3],
        xi_hat[2, 1], xi_hat[0, 2], xi_hat[1, 0],
    ])


def Ad(g: sp.Matrix) -> sp.Matrix:
    """Adjoint of g in SE(3), MLS convention: [[R, hat(p) @ R], [0, R]].

    Maps twists between frames. Note Ad(g)**-1 == Ad(se3_inv(g)), so the body
    composition rule can be written either way:
        V_b_nt = Ad(g_ft)**-1 @ V_b_nf + J_b @ theta_dot
    """
    R = g[:3, :3]
    return sp.Matrix(sp.BlockMatrix([
        [R, hat(g[:3, 3]) * R],
        [sp.zeros(3, 3), R],
    ]))


def body_jacobian(g: sp.Matrix, thetas) -> sp.Matrix:
    """Body Jacobian J_b, so that V_b = J_b @ theta_dot (twist in child frame).

    Column i is (se3_inv(g) @ dg/dtheta_i)^vee, which follows from the chain
    rule g_dot = sum_i (dg/dtheta_i) * theta_dot_i. No time symbol is needed --
    theta_dot only enters when the caller multiplies through.

    Physically, column i is the body twist generated by unit rate at joint i
    with all other joints locked, so each column can be checked on its own.
    """
    gi = se3_inv(g)
    return sp.Matrix.hstack(*[
        sp.trigsimp(vee_se3(sp.trigsimp(gi * g.diff(th)))) for th in thetas
    ])


def spatial_jacobian(g: sp.Matrix, thetas) -> sp.Matrix:
    """Spatial Jacobian J_s, so that V_s = J_s @ theta_dot (twist in base frame).

    Same construction as body_jacobian with the multiplication order swapped.
    WARNING: the linear part of a spatial twist is p_dot - omega x p, i.e. the
    velocity of the body-fixed point momentarily at the BASE origin, not the
    velocity of the child origin. Recover the latter with p_dot = v + omega x p.
    The body form has no such term (v_b == R.T @ p_dot), which is why the ESKF
    path below uses it.
    """
    gi = se3_inv(g)
    return sp.Matrix.hstack(*[
        sp.trigsimp(vee_se3(sp.trigsimp(g.diff(th) * gi))) for th in thetas
    ])


def main() -> None:
    # Chain runs foot body frame -> shank -> thigh body frame, i.e. up the leg
    # from the foot IMU to the thigh IMU. Both joint axes are +y (sagittal).
    #
    #   fo  = foot body frame   (frame the ESKF's self.fo.q attitude refers to)
    #   sh  = shank frame, origin at the knee
    #   th  = thigh body frame  (frame the ESKF's self.th.q attitude refers to)
    #
    # NOTE: these are BODY frames, not the WitMotion sensor frames. The fixed
    # sensor->body mount rotation is applied upstream of the filter; it is not
    # part of this chain. Neither is either IMU's estimated attitude.
    #
    # Foot body frame convention: +x forward (toward the toe), +z vertically up
    # (normal to the sole), +y completing right-handed => +y points left, which
    # is the sagittal axis rot_y rotates about.
    #
    # Consequences of that choice, worth verifying on hardware:
    #   theta_ankle = 0  -> shank vertical (neutral standing), NOT horizontal
    #   theta_ankle > 0  -> knee swings toward +x  => dorsiflexion
    #   theta_knee  = 0  -> thigh colinear with shank (leg straight)
    #   theta_knee  > 0  -> hip end of thigh swings toward +x => EXTENSION
    #   theta_knee  < 0  -> knee FLEXION
    #
    # That last one is the trap: standard biomech convention makes flexion
    # positive, this chain makes it negative, so the knee mapping below almost
    # certainly needs s_knee = -1.
    #
    # Encoder angles therefore need an explicit affine mapping into these
    # symbols (sign + zero offset per joint); do not feed ankle_angle /
    # knee_angle from convert_encoders() in raw:
    #
    #     theta_joint = s_joint * <encoder angle> + theta_joint_0
    #
    #   s_knee  = -1   CONFIRMED: encoders report flexion positive, this chain
    #                  makes flexion negative.
    #   s_ankle = -1   CONFIRMED on hardware (Jul 2026): encoders report
    #                  plantarflexion positive, this chain has dorsiflexion
    #                  positive.
    #   theta_knee_0  = 0   CONFIRMED: encoder zero is the extended-leg pose,
    #                  which is exactly this chain's zero (links colinear).
    #   theta_ankle_0 = 0   CONFIRMED to within a few degrees: the ankle zeroing
    #                  pose is natural standing, sole perpendicular to the
    #                  shank, which is this chain's zero (+z is the sole
    #                  normal). Note "natural standing" is eyeballed, not a
    #                  hard mechanical stop like the knee's extended pose, so a
    #                  small residual offset may remain -- see the calibration
    #                  check below.
    #
    # Net result: theta = -<encoder angle> for BOTH joints, so with encoder
    # angles a = ankle_angle, k = knee_angle the chain gives
    #     p_fo_th = [ -(l_shank*sin(a) + t_x*cos(a+k) + t_z*sin(a+k)),
    #                 t_y,
    #                 l_shank*cos(a) - t_x*sin(a+k) + t_z*cos(a+k) ]
    # (substituting -a, -k into the printed forms). Only the fore-aft component
    # flips sign; the vertical one is unchanged since cos is even.
    #
    # Calibration check before trusting any of this, since s_ankle is still
    # unverified and theta_ankle_0 is eyeballed:
    #     R_w_fo.T @ R_w_th  ==  rot_y(-(a + k))
    # Vary the joints INDEPENDENTLY across poses -- the identity constrains only
    # the sum, so it cannot localize a single bad sign on its own.
    theta_ankle, theta_knee = sp.symbols("theta_ankle theta_knee", real=True)
    l_shank = sp.symbols("l_shank", positive=True)
    t_x, t_y, t_z = sp.symbols("t_x t_y t_z", real=True)

    # Link offsets in each child frame; real values live in params.LEG.
    # ankle->knee is purely along the link, but knee->thigh IMU is NOT: the
    # thigh IMU is mounted off-axis, so it needs the full 3-vector. Its t_y is
    # invariant under rot_y, so it only adds a constant to p_fo_th[1] and the
    # Jacobians keep a zero y row.
    p_fo_sh = sp.Matrix([0, 0, l_shank])
    p_sh_th = sp.Matrix([t_x, t_y, t_z])

    g_fo_sh = g_rot_y(theta_ankle, p_fo_sh)
    g_sh_th = g_rot_y(theta_knee, p_sh_th)
    g_fo_th = sp.simplify(g_fo_sh * g_sh_th)

    sp.pprint(g_fo_sh)
    sp.pprint(g_sh_th)
    sp.pprint(g_fo_th)

    # Thigh body origin expressed in the foot body frame. This is the kinematic
    # measurement the ESKF needs: it ties self.th.p to self.fo.p via
    #     p_w_th - p_w_fo = R_w_fo @ p_fo_th(q)
    p_fo_th = g_fo_th[:3, 3]
    sp.pprint(sp.simplify(p_fo_th))

    # ---- differential kinematics -------------------------------------------
    # Body Jacobian: V_b_ft = J_b @ [theta_ankle_dot, theta_knee_dot].
    # Depends on theta_knee ONLY -- the body form is invariant to the base joint
    # angle, since it is written in a frame that rotates with the chain. The
    # spatial Jacobian carries theta_ankle in every entry by contrast.
    J_b = body_jacobian(g_fo_th, (theta_ankle, theta_knee))
    sp.pprint(J_b)

    # Rank drops where the sagittal (x, z) block goes singular: at theta_knee=0,
    # the straight leg. Both columns' linear parts become parallel there. That
    # pose is standing and near heel-strike, i.e. exactly when a kinematic update
    # is most wanted -- keep the measurement covariance honest rather than
    # pseudo-inverting through it.
    sp.pprint(sp.simplify(J_b[[0, 2], :].det()))

    # Velocity constraint for the ESKF, all in MLS body form:
    #
    #   V_b_nf = [R_nf.T @ v_nf ; omega_nf]   <- foot state + bias-corrected gyro
    #                                            (a gyro measures body angular
    #                                             velocity directly, so the
    #                                             angular half needs no transform)
    #   V_b_nt = Ad(g_fo_th)**-1 @ V_b_nf + J_b @ theta_dot
    #   v_nt   = R_nt @ V_b_nt[:3]            <- compare against self.th.v
    #
    # R_nt comes from the thigh IMU attitude, so the joint-motion term never
    # touches absolute nav position. NOTE theta_dot is in CHAIN convention, so
    # the s = -1 sign flips documented above apply to the rates too.




if __name__ == "__main__":
    main()
